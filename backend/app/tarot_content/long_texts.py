SECTION_MARKS = {
    "general": "Сейчас:",
    "advice": "Что поможет:",
    "outcome": "Возможное направление:",
}


def _sections(text: str) -> dict[str, str]:
    """Split an editorial block into role sections (deterministic parse)."""
    out: dict[str, str] = {}
    current = "general"
    buf: list[str] = []
    marks = {v: k for k, v in SECTION_MARKS.items()}
    for sentence in [s.strip() for s in text.split(".") if s.strip()]:
        matched = None
        for mark, role in marks.items():
            if sentence.startswith(mark):
                matched = role
                sentence = sentence[len(mark):].strip()
                break
        if matched is not None:
            out[current] = ". ".join(buf).strip()
            buf = []
            current = matched
        buf.append(sentence)
    out[current] = ". ".join(buf).strip() + ("." if buf else "")
    return {k: v for k, v in out.items() if v}


