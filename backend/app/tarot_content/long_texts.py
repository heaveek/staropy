def build_meaning_entries() -> list[MeaningDef]:
    """Adapt long-form blocks to MeaningDef rows.

    Universal section -> meaning_type 'general', theme=None.
    Themed sections   -> meaning_type 'general', theme=<code>, priority=10.
    Advice/outcome sentences inside the universal block additionally produce
    role-typed rows so position-role selection can pick coherent text.
    """
    entries: list[MeaningDef] = []
    for code, blocks in CARD_LONG.items():
        universal = blocks.get("general", "")
        if universal:
            sections = _sections(universal)
            entries.append(MeaningDef(code, None, "general",
                                      sections.get("general", universal),
                                      universal, priority=20))
            if "advice" in sections:
                entries.append(MeaningDef(code, None, "advice",
                                          sections["advice"], universal, priority=25))
            if "outcome" in sections:
                entries.append(MeaningDef(code, None, "outcome",
                                          sections["outcome"], universal, priority=25))
        for theme in THEMES:
            text = blocks.get(theme, "")
            if text:
                sections = _sections(text)
                short = sections.get("general") or text[:160].rsplit(".", 1)[0] + "."
                entries.append(MeaningDef(code, theme, "general", short, text,
                                          priority=30))
                if "advice" in sections:
                    entries.append(MeaningDef(code, theme, "advice",
                                              sections["advice"], text, priority=35))
                if "outcome" in sections:
                    entries.append(MeaningDef(code, theme, "outcome",
                                              sections["outcome"], text, priority=35))
    return entries
