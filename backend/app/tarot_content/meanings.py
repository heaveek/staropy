def all_card_tags() -> list[CardTagDef]:
    from .tags import TAGS
    known = {t.code for t in TAGS}
    out: list[CardTagDef] = []
    for card_code, tag_codes in CARD_TAGS_RAW:
        for tc in tag_codes:
            if tc in known:  # unknown placeholder codes are dropped at load time
                out.append(CardTagDef(card_code, tc))
    return out
