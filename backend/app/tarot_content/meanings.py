"""Editorial meaning content: general + themed meanings, yes/no signals, tags.

All texts are pre-written editorial blocks (neutral, reflection-oriented).
Nothing here is generated at runtime. `review_status` marks editorial state;
only `approved` blocks reach the user (spec §9.2, §16).
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class MeaningDef:
    card_code: str
    theme: str | None  # None => universal
    meaning_type: str  # general|resource|challenge|advice|outcome
    text_short: str
    text_long: str = ""
    priority: int = 0
    review_status: str = "approved"


@dataclass(frozen=True)
class YesNoDef:
    card_code: str
    answer: str  # yes|no|maybe
    text: str
    theme: str | None = None
    priority: int = 0
    review_status: str = "approved"


@dataclass(frozen=True)
class CardTagDef:
    card_code: str
    tag_code: str
    weight: int = 5
    source: str = "editorial"
    review_status: str = "approved"


